"""English currency names: code -> (unit, unit plural, subunit, subunit plural). None subunit = no fractional unit."""

from ...core.currencies import build_currencies


def _named(unit: str, plural: str | None = None, subunit: str | None = "cent", subunit_plural: str | None = None):
    return (
        unit,
        plural or unit + "s",
        subunit,
        (subunit_plural or subunit + "s") if subunit else None,
    )


def _whole(unit: str, plural: str | None = None):
    return _named(unit, plural, subunit=None)


def _dollar(country: str):
    return _named(f"{country} dollar")


def _same(word: str):
    return word, word


